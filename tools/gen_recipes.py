"""Builds src/data/RecipeData.lua from wago.tools DB2 CSV exports of a Classic Era build.

Usage: python3 -I gen_recipes.py <csv dir> <build> <out.lua>
The csv dir needs SkillLineAbility, SpellReagents, SpellEffect, SpellName, Item and ItemSparse
(https://wago.tools/db2/<Table>/csv?build=<build>).
"""
import csv, os, sys

SRC, BUILD, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
PROFS = {171: "Alchemy", 164: "Blacksmithing", 333: "Enchanting", 202: "Engineering",
         165: "Leatherworking", 197: "Tailoring", 185: "Cooking", 129: "First Aid",
         186: "Mining", 40: "Poisons"}
SEASONAL_FROM = 400000  # Season of Discovery recipes share the Era client; their spell IDs start here
CREATE_ITEM = 24


def rows(table):
    with open(os.path.join(SRC, table + ".csv"), newline="", encoding="utf-8") as f:
        yield from csv.DictReader(f)


names = {int(r["ID"]): r["Name_lang"] for r in rows("SpellName")}
items = {int(r["ID"]) for r in rows("Item")}
itemNames = {int(r["ID"]): r["Display_lang"] for r in rows("ItemSparse")}

reagents = {}
for r in rows("SpellReagents"):
    d = {}
    for i in range(8):
        item, count = int(r[f"Reagent_{i}"]), int(r[f"ReagentCount_{i}"])
        if item and count > 0 and item in items:
            d[item] = d.get(item, 0) + count
    if d:
        reagents[int(r["SpellID"])] = d

# Product and the minimum number made (what GetTradeSkillNumMade reports)
products = {}
for r in sorted(rows("SpellEffect"), key=lambda r: int(r["EffectIndex"])):
    if int(r["Effect"]) == CREATE_ITEM and int(r["EffectItemType"]) in items:
        sid = int(r["SpellID"])
        if sid not in products:
            made = int(r["EffectBasePoints"]) + (1 if int(r["EffectDieSides"]) >= 1 else 0)
            products[sid] = (int(r["EffectItemType"]), max(1, made))

recipes = {}
for r in rows("SkillLineAbility"):
    line, sid = int(r["SkillLine"]), int(r["Spell"])
    if line in PROFS and sid in reagents:
        p, c = products.get(sid, (0, 1))
        recipes[sid] = (PROFS[line], p, c, names.get(sid, ""), reagents[sid], int(r["MinSkillLineRank"]))


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


counts = {}
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- data/RecipeData.lua: every Classic Era profession recipe, generated by tools/gen_recipes.py\n")
    f.write(f"-- from wago.tools DB2 exports of build {BUILD}. Do not edit by hand.\n")
    f.write("-- [spellID] = { prof, product itemID (0 = enchant), number made, min skill, name, { itemID, count, ... }, seasonal }\n")
    f.write("local _, ns = ...\n")
    f.write(f'ns.RecipeDataBuild = "{BUILD}"\n')
    f.write("ns.RecipeData = {\n")
    for sid in sorted(recipes):
        prof, p, c, n, rg, skill = recipes[sid]
        counts[prof] = counts.get(prof, 0) + 1
        flat = ",".join(f"{i},{rg[i]}" for i in sorted(rg))
        season = ",true" if sid >= SEASONAL_FROM else ""
        f.write(f"[{sid}]={{{q(prof)},{p},{c},{skill},{q(n)},{{{flat}}}{season}}},\n")
    f.write("}\n")
    # English names of every product and reagent, so name searches work before the client caches items
    used = sorted({p for _, p, _, _, _, _ in recipes.values() if p} | {i for r in recipes.values() for i in r[4]})
    f.write("ns.ItemNames = {\n")
    for i in used:
        if itemNames.get(i):
            f.write(f"[{i}]={q(itemNames[i])},\n")
    f.write("}\n")

print(len(recipes), "recipes", dict(sorted(counts.items())))
