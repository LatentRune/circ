"""Builds src/data/BoeData.lua: names of every tradeable Bind-on-Equip item in Classic Era, so
Lookup can suggest BoE gear nobody in the ledger has listed yet.

Usage: python3 -I gen_boe.py <csv dir> <build> <out.lua>
The csv dir needs Item and ItemSparse (https://wago.tools/db2/<Table>/csv?build=<build>).
Kept: Bind on Equip (Bonding 2), equippable (InventoryType > 0), quality uncommon or better,
plus unbound or BoE recipes, patterns and plans (ClassID 9) of any quality.
"""
import csv, os, re, sys

SRC, BUILD, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
BOE, UNBOUND = 2, 0
RECIPE_CLASS = 9


def rows(table):
    with open(os.path.join(SRC, table + ".csv"), newline="", encoding="utf-8") as f:
        yield from csv.DictReader(f)


def num(r, *keys):
    for k in keys:
        if k in r and r[k] != "":
            return int(float(r[k]))
    return 0


# Names of items players never see: placeholders, test gear and leftovers, such as
# "zzOLDCodex of Prayer of Fortitude", "S03 - Scarlet Enclave - Sword 1h" or "90 Epic Warrior Gun"
INTERNAL = re.compile(r"^(Deprecated|Monster -|OLD|Test |zz|UNUSED)|^S\d\d - |^\d+ (Epic|Green|Blue) |TEST|\bOLD$|\[PH\]")


itemClass = {int(r["ID"]): num(r, "ClassID") for r in rows("Item")}
keep = {}
for r in rows("ItemSparse"):
    iid, name = int(r["ID"]), r["Display_lang"].strip()
    if not name or iid not in itemClass or INTERNAL.search(name):
        continue
    bonding = num(r, "Bonding")
    quality = num(r, "OverallQualityID")
    if itemClass[iid] == RECIPE_CLASS and bonding in (UNBOUND, BOE):
        keep[iid] = name
    elif bonding == BOE and num(r, "InventoryType") > 0 and quality >= 2:
        keep[iid] = name


def esc(s):
    return s.replace("\\", "\\\\").replace("\n", " ").replace("\t", " ")


with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- data/BoeData.lua: names of tradeable Bind-on-Equip gear and recipes, generated by tools/gen_boe.py\n")
    f.write(f"-- from wago.tools DB2 exports of build {BUILD}. Do not edit by hand.\n")
    f.write("-- One \"id<TAB>name\" per line; Lookup reads it into ns.ItemNames on load.\n")
    f.write("local _, ns = ...\n")
    f.write("ns.BoeData = [==[\n")
    for iid in sorted(keep):
        f.write(f"{iid}\t{esc(keep[iid])}\n")
    f.write("]==]\n")

print(len(keep), "items")
